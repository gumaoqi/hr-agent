"""生成 3 份测试简历 PDF（用于简历筛选功能端到端验证）"""
import os
from fpdf import FPDF

FONT = r"C:\Windows\Fonts\simhei.ttf"
OUT_DIR = os.path.dirname(os.path.abspath(__file__))

def make_resume(file_name, name, body_lines):
    pdf = FPDF()
    pdf.add_font("hei", "", FONT)
    pdf.add_page()
    pdf.set_font("hei", "", 20)
    pdf.cell(190, 12, name, ln=True)
    pdf.set_font("hei", "", 11)
    for line in body_lines:
        pdf.multi_cell(190, 7, line)
    path = os.path.join(OUT_DIR, file_name)
    pdf.output(path)
    print("created:", path)

